const blocked = [
  /(?:ул\.?|улиц[аыеу]|проспект|пр-т|дом|д\.?|квартира|кв\.?|подъезд|корпус)\s+(?:[А-Яа-яЁёA-Za-z.-]+\s+)?\d+/i,
  /\+?\d[\d\s()\-]{8,}\d/,
  /(погиб|смерт|ранен|пострадал|трагеди|убийств|арест|преступлен|авари|больниц)/i,
  /\S+@\S+\.\S+/,
];

export function isSafeSatire(value: string) {
  const text = value.trim();
  return Boolean(text) && text.length <= 800 && !blocked.some((pattern) => pattern.test(text));
}

